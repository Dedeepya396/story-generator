import os
import json

from dotenv import load_dotenv
from groq import Groq


load_dotenv()

api_key = os.getenv("GROQ_API_KEY")

if not api_key:
    raise Exception("GROQ_API_KEY not found")

client = Groq(api_key=api_key)


def generate_quiz_from_story(story: str, language: str = "english", video_duration: float | int | str | None = None):
    target_count = None
    if video_duration is not None:
        try:
            v_dur = float(video_duration)
            if v_dur > 0:
                # Minimum 5 questions. Adds +1 question per 12 seconds of video above 30s, up to 12 max.
                target_count = max(5, min(12, 5 + int(max(0.0, v_dur - 30.0) // 12)))
        except (ValueError, TypeError):
            target_count = None

    if target_count is None:
        words = story.strip().split()
        word_count = len(words)
        # Minimum 5 questions. Adds +1 question per 20 words above 50 words, up to 12 max.
        target_count = max(5, min(12, 5 + max(0, (word_count - 50) // 20)))

    prompt = f"""
You are an educational quiz generator for children.

Read the story below and create exactly {target_count} diverse questions testing comprehension.
Include a variety of question types across the {target_count} questions:
- "mcq" (Multiple Choice Question): 4 options, 1 correct option index (0, 1, 2, or 3).
- "true_false" (True or False Question): 2 options representing True and False in {language}, 1 correct option index (0 or 1).
- "fill_blank" (Fill in the Blank Question): Sentence text containing a blank "_____", 4 word options to fill the blank, 1 correct option index (0, 1, 2, or 3).

Language requirement:
- The entire quiz (all question texts, statements, and option texts) MUST be written in the {language} language.
- If {language} is not English (such as Hindi, Telugu, Tamil, Malayalam, Kannada, Bengali, Gujarati, Marathi, Punjabi, Odia, Assamese, etc.), generate all questions and options directly in {language}.

Return ONLY valid JSON using this format:

{{
    "questions": [
        {{
            "type": "mcq",
            "question": "Question text in {language}",
            "options": [
                "Option 1 in {language}",
                "Option 2 in {language}",
                "Option 3 in {language}",
                "Option 4 in {language}"
            ],
            "answer": 0
        }},
        {{
            "type": "true_false",
            "question": "Statement text in {language}",
            "options": [
                "True text in {language}",
                "False text in {language}"
            ],
            "answer": 0
        }},
        {{
            "type": "fill_blank",
            "question": "Sentence with _____ in {language}",
            "options": [
                "Word 1 in {language}",
                "Word 2 in {language}",
                "Word 3 in {language}",
                "Word 4 in {language}"
            ],
            "answer": 0
        }}
    ]
}}

STORY:
{story}
"""

    models_to_try = [
        "groq/compound-mini",
        "qwen/qwen3.6-27b",
        "groq/compound",
        "openai/gpt-oss-20b"
    ]

    content = None
    last_err = None

    for model_name in models_to_try:
        try:
            print(f"Generating quiz ({target_count} questions) using Groq model: {model_name} (language: {language})...")
            response = client.chat.completions.create(
                model=model_name,
                messages=[
                    {
                        "role": "system",
                        "content": f"You generate educational quizzes for children with diverse question types in {language} language. Output strict valid JSON."
                    },
                    {
                        "role": "user",
                        "content": prompt
                    }
                ],
                temperature=0.3,
                response_format={"type": "json_object"}
            )
            content = response.choices[0].message.content
            if content:
                break
        except Exception as e:
            print(f"Groq model {model_name} failed: {e}")
            last_err = e

    if not content:
        raise Exception(f"All Groq models failed to generate quiz: {last_err}")

    try:
        quiz = json.loads(content)
    except Exception as e:
        # Fallback: extract json substring if wrapped in markdown
        import re
        m = re.search(r'(\{.*\})', content, re.S)
        if m:
            quiz = json.loads(m.group(1))
        else:
            raise Exception(f"Failed to parse JSON response: {e}")

    if not isinstance(quiz, dict) or "questions" not in quiz or not isinstance(quiz["questions"], list):
        raise Exception("Invalid quiz format returned by model")

    raw_questions = quiz["questions"]
    if len(raw_questions) == 0:
        raise Exception("No questions generated by model")

    sanitized_questions = []
    for q in raw_questions[:target_count]:  # cap at target_count questions max
        if not isinstance(q, dict) or "question" not in q:
            continue
        
        q_text = str(q.get("question", "")).strip()
        if not q_text:
            continue

        q_type = str(q.get("type", "mcq")).lower()
        if q_type not in ["mcq", "true_false", "fill_blank"]:
            q_type = "mcq"

        options = q.get("options", [])
        if not isinstance(options, list):
            options = []
        options = [str(opt).strip() for opt in options if str(opt).strip()]

        if q_type == "true_false":
            if len(options) < 2:
                options = ["True", "False"]
            elif len(options) > 2:
                options = options[:2]
        else:
            if len(options) < 2:
                continue
            elif len(options) > 4:
                options = options[:4]

        # Ensure answer index is valid integer
        ans = 0
        try:
            ans = int(q.get("answer", 0))
            if ans < 0 or ans >= len(options):
                ans = 0
        except (ValueError, TypeError):
            ans = 0

        sanitized_questions.append({
            "type": q_type,
            "question": q_text,
            "options": options,
            "answer": ans
        })

    if not sanitized_questions:
        raise Exception("Could not build valid quiz questions")

    return {"questions": sanitized_questions}